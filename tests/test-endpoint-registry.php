<?php
/**
 * Endpoint registry tests.
 *
 * @package Pantheon\AshNazg
 */

use PHPUnit\Framework\TestCase;

/**
 * Test the generated Pantheon API endpoint registry.
 */
class Test_Endpoint_Registry extends TestCase {

	/**
	 * Load the registry.
	 *
	 * @return array List of [ version, method, path, summary, group ] entries.
	 */
	private function registry() {
		// The registry file exits when loaded outside WordPress; it has no other side effects.
		if ( ! defined( 'ABSPATH' ) ) {
			define( 'ABSPATH', __DIR__ . '/' );
		}

		return include dirname( ASH_NAZG_PLUGIN_FILE ) . '/includes/endpoints-registry.php';
	}

	/**
	 * Test every entry has the documented shape.
	 */
	public function test_entries_are_well_formed() {
		$registry = $this->registry();

		$this->assertNotEmpty( $registry );

		foreach ( $registry as $entry ) {
			$this->assertCount( 5, $entry );
			$this->assertContains( $entry[0], [ 'v0', 'v1' ], 'version' );
			$this->assertContains( $entry[1], [ 'GET', 'POST', 'PUT', 'PATCH', 'DELETE' ], 'method' );
			$this->assertStringStartsWith( '/', $entry[2], 'path' );
			$this->assertNotSame( '', $entry[4], 'group' );
		}
	}

	/**
	 * Test no endpoint is listed twice.
	 */
	public function test_entries_are_unique() {
		$keys = array_map(
			function ( $entry ) {
				return $entry[0] . ' ' . $entry[1] . ' ' . $entry[2];
			},
			$this->registry()
		);

		$this->assertSame( $keys, array_values( array_unique( $keys ) ) );
	}

	/**
	 * Test both API versions are covered, and the registry includes endpoints that fail.
	 *
	 * The page reports broken endpoints too, so the registry lists every operation
	 * the specs publish, not only the ones known to work.
	 */
	public function test_covers_both_versions_and_known_endpoints() {
		$registry = $this->registry();
		$versions = array_unique( array_column( $registry, 0 ) );
		sort( $versions );

		$this->assertSame( [ 'v0', 'v1' ], $versions );
		$this->assertContains( [ 'v1', 'GET', '/current-user' ], array_map( function ( $e ) {
			return array_slice( $e, 0, 3 );
		}, $registry ) );
	}

	/**
	 * Test the file says it is generated, so nobody edits it by hand.
	 */
	public function test_file_is_marked_generated() {
		$contents = file_get_contents( dirname( ASH_NAZG_PLUGIN_FILE ) . '/includes/endpoints-registry.php' );

		$this->assertStringContainsString( 'GENERATED by bin/generate-endpoint-registry.py', $contents );
	}
}
