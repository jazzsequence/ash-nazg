#!/usr/bin/env python3
"""
Generate includes/endpoints-registry.php from Pantheon's published API specs.

The dashboard lists every endpoint the API offers and probes the safe reads.
Regenerate this file when Pantheon changes either API:

    python3 bin/generate-endpoint-registry.py

Sources (the only documentation for the Pantheon API, per CLAUDE.md):
    https://api.pantheon.io/docs/swagger.json   (v0)
    https://api.pantheon.io/v1/openapi.json     (v1)
"""

import json
import re
import sys
import urllib.request

SPECS = [
    ('v0', 'https://api.pantheon.io/docs/swagger.json', '/v0'),
    ('v1', 'https://api.pantheon.io/v1/openapi.json', ''),
]

METHODS = ('get', 'post', 'put', 'patch', 'delete')

# Canonical placeholder for each path parameter name, per API version.
PLACEHOLDERS = {
    'siteId': 'site_id',
    'site_id': 'site_id',
    'environment': 'env',
    'env': 'env',
    'env_id': 'env',
    'userId': 'user_id',
    'user_id': 'user_id',
    'workspaceId': 'workspace_id',
    'org_id': 'workspace_id',
    'siteName': 'site_name',
    'site_name': 'site_name',
    'workflowId': 'workflow_id',
    'workflow_id': 'workflow_id',
    'buildId': 'build_id',
    'backup_id': 'backup_id',
    'key_id': 'key_id',
}

# Required query parameters on reads, and the value to probe with.
QUERY_DEFAULTS = {
    'first': '10',
    'startTime': '{start_time}',
}

# First match wins.
GROUPS = [
    ('Secrets', r'/secrets'),
    ('Upstreams', r'^/upstreams|/upstream(-updates|/)|/upstream$|/build/updates'),
    ('Workflows', r'/workflows'),
    ('Backups', r'/backup'),
    ('Domains', r'/domains|/primary-domain'),
    ('Metrics', r'/metrics'),
    ('Builds & Logs', r'/builds|/runtime-logs|/tenant-runtime-log'),
    ('Imports & Exports', r'/imports?(/|-)|/imports?$|/exports?(/|-)|/exports?$'),
    ('Addons', r'/addons'),
    ('Multidevs & Branches', r'/multidevs|/git-branches|/code-tips|/multidev-names|/merges?|/merge-from-dev'),
    ('Workspaces & Organizations', r'^/(workspaces|organizations)'),
    ('Account & User', r'^/(current-user|authorize|users)'),
    ('Team & Access', r'/users|/memberships|/authorizations|/leave|/owner|/payment-method|/plan|/available-plans'),
    ('Environments', r'/environments|/deploy'),
    ('Sites', r'^/(sites|site-names)'),
]


def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'ash-nazg-registry-generator/1.0'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def canonical_path(path, version):
    """Rewrite spec path parameters to the canonical placeholders."""
    def replace(match):
        name = match.group(1)
        if name == 'id':
            # v1 uses a bare {id} for upstreams and builds.
            return '{upstream_id}' if '/upstreams/' in path else '{build_id}'
        if name == 'name':
            return '{multidev_name}' if 'multidev' in path else '{name}'
        return '{' + PLACEHOLDERS.get(name, re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()) + '}'

    return re.sub(r'\{(\w+)\}', replace, path)


def group_for(path):
    for name, pattern in GROUPS:
        if re.search(pattern, path):
            return name
    return 'Other'


def php_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    entries = []

    for version, url, prefix in SPECS:
        spec = fetch(url)
        for raw_path, item in spec['paths'].items():
            path = raw_path[len(prefix):] if prefix and raw_path.startswith(prefix) else raw_path
            for method in METHODS:
                operation = item.get(method)
                if not operation:
                    continue

                canonical = canonical_path(path, version)

                if method == 'get':
                    required = [
                        p['name'] for p in operation.get('parameters', [])
                        if p.get('in') == 'query' and p.get('required')
                    ]
                    pairs = []
                    for name in required:
                        pairs.append('%s=%s' % (name, QUERY_DEFAULTS.get(name, '{%s}' % name)))
                    if pairs:
                        canonical += '?' + '&'.join(pairs)

                summary = operation.get('summary') or operation.get('operationId') or ''
                entries.append((group_for(canonical), version, method.upper(), canonical, summary))

    order = [name for name, _ in GROUPS] + ['Other']
    entries.sort(key=lambda e: (order.index(e[0]), e[3], e[1], e[2]))

    lines = [
        '<?php',
        '/**',
        ' * Pantheon API endpoint registry.',
        ' *',
        ' * GENERATED by bin/generate-endpoint-registry.py from the v0 and v1 specs.',
        ' * Do not edit by hand; regenerate it when Pantheon changes either API.',
        ' *',
        ' * Each entry: [ version, method, path, summary, group ]. Paths omit the /v0',
        ' * prefix and use canonical {placeholders} that probe_registry_entry() resolves.',
        ' *',
        ' * @package Pantheon\\AshNazg',
        ' */',
        '',
        '// Exit if accessed directly.',
        "if ( ! defined( 'ABSPATH' ) ) {",
        '\texit;',
        '}',
        '',
        'return [',
    ]
    for group, version, method, path, summary in entries:
        lines.append('\t[ %s, %s, %s, %s, %s ],' % (
            php_string(version), php_string(method), php_string(path), php_string(summary), php_string(group)
        ))
    lines += ['];', '']

    target = sys.argv[1] if len(sys.argv) > 1 else 'includes/endpoints-registry.php'
    with open(target, 'w') as handle:
        handle.write('\n'.join(lines))

    counts = {}
    for entry in entries:
        counts[entry[0]] = counts.get(entry[0], 0) + 1
    print('%d endpoints written to %s' % (len(entries), target))
    for name in order:
        if name in counts:
            print('  %-28s %d' % (name, counts[name]))


if __name__ == '__main__':
    main()
